"""Отправить HTML-превью письма основателя после квиза/пробного доступа.

Локально (нужен .env с SMTP):
  python scripts/send_founder_trial_preview.py

На сервере:
  docker compose exec -T api python scripts/send_founder_trial_preview.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from notifications.email_channel import send_email  # noqa: E402

TO = "info@chitatelstvo.ru"
HTML_PATH = ROOT / "docs" / "email-templates" / "founder-trial-letter-example.html"
SUBJECT = "Виолетта и чтение — мои рекомендации от Ольги"

PLAIN = """Татьяна, здравствуйте!

Рада, что Виолетта теперь с нами в Читательстве. Спасибо, что прошли короткий опрос — по вашим ответам видно, что сейчас важнее всего понимать, о чём текст, а не гоняться за скоростью.

Я придумала Читательство, потому что вижу по своим детям: книга может конкурировать с гаджетами, если читать вместе интересно — без давления. Нам важнее, чтобы ребёнок понял героя, его чувства и поступки.

Все занятия я сначала проверяю дома. Если что-то скучно или непонятно — переделываем.

——— Мои предложения именно вам ———
Попробуйте пройти урок по сказке «Царевна-лягушка» — я открыла доступ именно к этому уроку. Там мягкий вход в вопросы по тексту: можно ошибаться, главное — понять героя. Если после первого занятия захотите совет — просто ответьте на письмо.
———————————————————————————————

Рекомендую начать с: 1 класс · программа «Сказки и смысл»
Пробный урок «Царевна-лягушка» уже открыт.

Открыть урок: https://api.chitatelstvo.ru/lesson/EXAMPLE
Личная страница Виолетты: https://api.chitatelstvo.ru/progress/EXAMPLE

С чего начать:
1. Откройте сказку «Царевна-лягушка» на странице прогресса.
2. Виолетта смотрит видео и отвечает на вопросы в том же окне.
3. Загляните в «Словики» и трофеи — там видно, что уже получилось.

Если удобнее заниматься с живым преподавателем — напишите, поставим в лист ожидания. Или начните с одной сказки на сайте — без обязательств на весь модуль.

Про пробный доступ: если Виолетта не заходит на платформу 30 дней подряд, пробный кабинет мы удаляем. Любой урок или вход в кабинет обновляет этот срок.

Дальше на сайте: https://chitatelstvo.ru/1-klass

Ближайшие встречи:
Рекомендую посмотреть курс «Ветер в ивах» — скоро стартует с преподавателем в группе: https://chitatelstvo.ru/veter-v-ivah

С теплом,
Ольга
Читательство

Если останутся вопросы — просто ответьте на это письмо.

lessons@chitatelstvo.ru · info@chitatelstvo.ru · chitatelstvo.ru
"""


def main() -> None:
    html = HTML_PATH.read_text(encoding="utf-8")
    send_email(
        TO,
        subject=f"{SUBJECT} — превью",
        body=PLAIN,
        html_body=html,
    )
    print(f"OK: sent to {TO}")


if __name__ == "__main__":
    main()
