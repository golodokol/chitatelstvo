def count_questions(data: dict) -> dict[str, int]:
    return {
        "comprehension": len(data.get("comprehension_quiz", {}).get("questions", [])),
        "meaning": len(data.get("meaning_quiz", {}).get("questions", [])),
        "reading_cards": len(data.get("reading_practice", {}).get("cards", [])),
        "retelling_events": len(
            data.get("retelling_quiz", {}).get("questions", [{}])[0].get("items", [])
        ),
        "creative": len(data.get("creative_tasks", {}).get("items", [])),
    }


def main() -> None:
    summary = []
    for filename, builder, title, tale_title, note in LESSONS:
        data = write_lesson(filename, builder(), title=title, tale_title=tale_title, note=note)
        counts = count_questions(data)
        ok = data.get("active") is True and "comprehension_quiz" in data
        summary.append((filename, data.get("title"), counts, ok))
        print(
            f"{'OK' if ok else 'FAIL'} {filename}: "
            f"comp={counts['comprehension']} meaning={counts['meaning']} "
            f"read={counts['reading_cards']} retell={counts['retelling_events']} "
            f"creative={counts['creative']}"
        )

    print("\n=== SUMMARY ===")
    print(f"written: {len(summary)}")
    print(f"all active+comprehension: {all(s[3] for s in summary)}")
    for filename, title, counts, ok in summary:
        print(f"- {filename} | {title} | {counts} | active_ok={ok}")


if __name__ == "__main__":
    main()
