def opt(oid: str, text: str, **extra: Any) -> dict:
    d = {"id": oid, "text": text}
    d.update(extra)
    return d


def video(title: str, duration: str = "8-12") -> dict:
    return {
        "type": "kinescope",
        "id": "",
        "title": title,
        "duration_min": duration,
        "pass_condition": "просмотр >= 50%",
    }


def live(quest: str | None = None) -> dict:
    d: dict[str, Any] = {
        "next_meeting_label": None,
        "price_rub": 799,
        "meeting_url": None,
        "enabled": False,
    }
    if quest:
        d["quest_idea"] = quest
    return d


def card(cid: str, text: str, folder: str, n: str, alt: str) -> dict:
    return {
        "id": cid,
        "text": text,
        "image": f"/static/lessons/{folder}/reading/reading-{n}.png",
        "alt": alt,
    }


def ev(eid: str, text: str, folder: str, n: str, alt: str) -> dict:
    return {
        "id": eid,
        "text": text,
        "image": f"/static/lessons/{folder}/event-{n}.png",
        "alt": alt,
    }


def emotion(
    character: str,
    text: str,
    correct: list[str],
    ok: str,
    hint: str,
    retry: str,
    *,
    min_correct: int | None = None,
) -> dict:
    q: dict[str, Any] = {
        "id": "e1",
        "text": text,
        "pick": 2,
        "correct": correct,
    }
    if min_correct is not None:
        q["min_correct"] = min_correct
    return {
        "title": "Эмоции героя",
        "character": character,
        "question": q,
        "feedback_ok": ok,
        "feedback_retry_hint": hint,
        "feedback_retry": retry,
    }


def ordering(items: list[dict], hint: str | None = None) -> dict:
    q: dict[str, Any] = {
        "id": "r1",
        "type": "ordering",
        "text": "Расставь события по порядку.",
        "items": items,
        "correct": [i["id"] for i in items],
    }
    if hint:
        q["hint"] = hint
    return {
        "title": "Пробуем пересказать сказку",
        "pass_score": 1,
        "questions": [q],
    }


def write_lesson(
    filename: str,
    content: dict,
    *,
    title: str | None = None,
    tale_title: str | None = None,
    note: str | None = None,
) -> dict:
    path = CATALOG / filename
    stub = json.loads(path.read_text(encoding="utf-8"))
    out: dict[str, Any] = {k: stub[k] for k in META_KEEP if k in stub}
    out["active"] = True
    out["status"] = "тест"
    out["title"] = title if title is not None else stub.get("title")
    out["tale_title"] = tale_title if tale_title is not None else stub.get("tale_title", out["title"])
    if note is not None:
        out["note"] = note
    elif "note" in stub:
        out["note"] = stub["note"]
    out.update(deepcopy(content))
    # ensure flags after content merge
    out["active"] = True
    out["status"] = "тест"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return out


