def js_literal(obj: object, indent: int = 4) -> str:
    raw = json.dumps(obj, ensure_ascii=False, indent=2)
    # Quote keys with single quotes to match file style where practical
    return raw.replace("\n", "\n" + " " * indent)


def patch_data() -> None:
    text = DATA.read_text(encoding="utf-8")
    start = text.index("    'wind': {")
    end = text.index("    'rus-6-9': {")
    wind_js = "    'wind': " + js_literal(WIND, 4) + ",\n"
    garden_js = "    'garden': " + js_literal(GARDEN, 4) + ",\n"
    DATA.write_text(text[:start] + wind_js + garden_js + text[end:], encoding="utf-8")
    print("patched course-lite-data.js")


def patch_seo() -> None:
    seo = json.loads(SEO.read_text(encoding="utf-8"))
    wind = seo["lite"]["wind"]
    garden = seo["lite"]["garden"]
    wind["lessons"] = [x["title"] for x in WIND["lessons"]]
    garden["lessons"] = [x["title"] for x in GARDEN["lessons"]]
    wind["intro"] = WIND["intro"]
    garden["intro"] = GARDEN["intro"]
    for key in (
        "aboutBook",
        "aboutAuthor",
        "aboutBookTitle",
        "aboutAuthorTitle",
    ):
        wind[key] = WIND[key]
        garden[key] = GARDEN[key]
    SEO.write_text(json.dumps(seo, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("patched course-seo.json")


if __name__ == "__main__":
    patch_data()
    patch_seo()
